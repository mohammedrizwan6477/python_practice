

# arithmetic operators
a = 10
b = 2
print("a + b = ", a + b)
print("a - b = ", a - b)
print("a * b = ", a * b)
print("a / b = ", a / b)
print("a % b = ", a % b)
print("a // b = ", a // b)
print("a ** b = ", a ** b)

# conditional operators

print(a > b) # true
print(a < b) # false
print(a <= 5) # false
print(a >= 10) # true
print(a == b) # false
print(a == 10) # true
print( a!= 10) # false


# Logical Operators

c = True
d = False
        # and
print(c and c) # true
print(c and d) # false
print(d and d) # false
print(d and c) # false

        # or
print(c or c) # true
print(c or d) # true
print(d or d) # false
print(d or c) # true   

        # not operators
